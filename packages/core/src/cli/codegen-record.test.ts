import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import { afterEach, describe, expect, it } from "vitest"
import { commitRuns, type Run } from "./codegen-record.ts"

const made: string[] = []
afterEach(() => {
	for (const dir of made.splice(0)) fs.rmSync(dir, { force: true, recursive: true })
})

const GENERATED = "/* @generated by comb — do not edit. checksum: x */\nexport {}\n"

/** A fresh directory holding `files`, by path relative to it */
function dirWith(files: Record<string, string>): string {
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), "comb-record-"))
	made.push(dir)
	for (const [name, text] of Object.entries(files)) {
		fs.mkdirSync(path.dirname(path.join(dir, name)), { recursive: true })
		fs.writeFileSync(path.join(dir, name), text)
	}
	return dir
}

const run = (dir: string, over: Partial<Run> = {}): Run => ({
	name: "core",
	partial: false,
	prefix: "db.core",
	root: path.join(dir, "src/db"),
	wrote: [],
	...over,
})
const record = (dir: string) =>
	JSON.parse(fs.readFileSync(path.join(dir, ".comb.codegen.gen.json"), "utf8")) as {
		databases: Record<string, string[]>
	}

describe("commitRuns", () => {
	it("writes what it staged, records it by database, and removes what the last run wrote and this one did not", () => {
		const dir = dirWith({})
		const fresh = path.join(dir, "src/db/db.core.rows.gen.ts")
		commitRuns(new Map([[fresh, GENERATED]]), [run(dir, { wrote: [fresh] })], { recordDir: dir })
		expect(record(dir).databases["core"]).toEqual(["src/db/db.core.rows.gen.ts"])
		const moved = path.join(dir, "src/gen/app.core.rows.gen.ts")
		commitRuns(new Map([[moved, GENERATED]]), [run(dir, { prefix: "app.core", wrote: [moved] })], { recordDir: dir })
		expect(fs.existsSync(fresh)).toBe(false)
		/* the old root, empty now, goes too */
		expect(fs.existsSync(path.join(dir, "src/db"))).toBe(false)
		expect(record(dir).databases["core"]).toEqual(["src/gen/app.core.rows.gen.ts"])
	})

	it("reads 0.9's record once, removing its stale files and the record itself", () => {
		const dir = dirWith({
			"src/db/.db.core.codegen.json": JSON.stringify({ files: ["db.core.old.gen.ts", "db.core.mine.ts"] }),
			"src/db/db.core.mine.ts": "export const mine = 1\n",
			"src/db/db.core.old.gen.ts": GENERATED,
			"src/db/db.core.tables.ts": "export {}\n",
		})
		commitRuns(new Map(), [run(dir)], { recordDir: dir })
		expect(fs.existsSync(path.join(dir, "src/db/db.core.old.gen.ts"))).toBe(false)
		/* a file comb did not write stays, whatever a record says */
		expect(fs.existsSync(path.join(dir, "src/db/db.core.mine.ts"))).toBe(true)
		expect(fs.existsSync(path.join(dir, "src/db/.db.core.codegen.json"))).toBe(false)
	})

	it("only adds to the record on a run of some generators, and keeps every other database's entry", () => {
		const dir = dirWith({ "src/db/db.core.rows.gen.ts": GENERATED })
		const kept = path.join(dir, "src/db/db.core.rows.gen.ts")
		commitRuns(new Map([[kept, GENERATED]]), [run(dir, { wrote: [kept] }), run(dir, { name: "audit" })], {
			recordDir: dir,
		})
		const added = path.join(dir, "src/db/db.core.manifest.gen.json")
		commitRuns(new Map([[added, "{}"]]), [run(dir, { partial: true, wrote: [added] })], { recordDir: dir })
		expect(fs.existsSync(kept)).toBe(true)
		expect(record(dir).databases).toEqual({
			audit: [],
			core: ["src/db/db.core.manifest.gen.json", "src/db/db.core.rows.gen.ts"],
		})
	})
})

describe("commitRuns: what each database owns (F14, F15, F16)", () => {
	it("on a run of the whole config, removes the files of a database the config no longer declares", () => {
		const dir = dirWith({})
		const aux = path.join(dir, "src/db/db.aux.rows.gen.ts")
		commitRuns(new Map([[aux, GENERATED]]), [run(dir, { name: "aux", wrote: [aux] })], { recordDir: dir })
		const core = path.join(dir, "src/db/db.core.rows.gen.ts")
		/* a run that names its databases leaves the others alone */
		commitRuns(new Map([[core, GENERATED]]), [run(dir, { wrote: [core] })], { recordDir: dir })
		expect(fs.existsSync(aux)).toBe(true)
		commitRuns(new Map([[core, GENERATED]]), [run(dir, { wrote: [core] })], { declared: ["core"], recordDir: dir })
		expect(fs.existsSync(aux)).toBe(false)
		expect(Object.keys(record(dir).databases)).toEqual(["core"])
	})

	it("keeps a file one database stops writing and another starts writing in the same run", () => {
		const dir = dirWith({})
		const manifest = path.join(dir, "manifest.gen.json")
		const json = `${JSON.stringify({ _generated: "comb checksum:x" })}\n`
		commitRuns(new Map([[manifest, json]]), [run(dir, { wrote: [manifest] })], { recordDir: dir })
		commitRuns(new Map([[manifest, json]]), [run(dir), run(dir, { name: "aux", wrote: [manifest] })], {
			recordDir: dir,
		})
		expect(fs.existsSync(manifest)).toBe(true)
		expect(record(dir).databases["aux"]).toEqual(["manifest.gen.json"])
	})

	it("fails, naming both databases and the path, when two stage one file", () => {
		const dir = dirWith({})
		const shared = path.join(dir, "src/db/db.app.rows.gen.ts")
		expect(() =>
			commitRuns(
				new Map([[shared, GENERATED]]),
				[run(dir, { wrote: [shared] }), run(dir, { name: "aux", wrote: [shared] })],
				{
					recordDir: dir,
				},
			),
		).toThrow(
			/^databases core and aux both write src\/db\/db\.app\.rows\.gen\.ts; give each its own filePrefix or output$/,
		)
		expect(fs.existsSync(shared)).toBe(false)
	})
})

describe("commitRuns: the record's own form (F30, F32)", () => {
	it("records the databases by name, whatever order they ran in", () => {
		const dir = dirWith({})
		commitRuns(new Map(), [run(dir, { name: "core" }), run(dir, { name: "aux" })], { recordDir: dir })
		expect(Object.keys(record(dir).databases)).toEqual(["aux", "core"])
	})

	it("says which file is not JSON, and that deleting it is safe", () => {
		const dir = dirWith({ ".comb.codegen.gen.json": "<<<<<<< HEAD\n{}\n" })
		expect(() => commitRuns(new Map(), [run(dir)], { recordDir: dir })).toThrow(
			/^\.comb\.codegen\.gen\.json is not JSON \(a merge conflict\?\): delete it, and the next run removes nothing stale; /,
		)
	})
})

/* the 0.12 review's F20 and F21: a run of some databases against what another database's record lists */
/** The manifest path two databases are given in the F20 and F21 cases */
const manifestOf = (dir: string) => path.join(dir, "src/shared/manifest.gen.json")

describe("commitRuns: a path another database's record lists (F20, F21)", () => {
	const json = `${JSON.stringify({ _generated: "comb checksum:x" })}\n`

	it("refuses a run that writes a path another database's record lists, naming both, and writes nothing", () => {
		const dir = dirWith({})
		const manifest = manifestOf(dir)
		commitRuns(new Map([[manifest, json]]), [run(dir, { name: "aux", wrote: [manifest] })], { recordDir: dir })
		const rows = path.join(dir, "src/db/db.core.rows.gen.ts")
		expect(() =>
			commitRuns(
				new Map([
					[manifest, json],
					[rows, GENERATED],
				]),
				[run(dir, { wrote: [manifest, rows] })],
				{ recordDir: dir },
			),
		).toThrow("databases aux and core both write src/shared/manifest.gen.json; give each its own filePrefix or output")
		expect(fs.existsSync(rows)).toBe(false)
	})

	it("deletes no file another database's record lists, even one this database's last run wrote", () => {
		const dir = dirWith({})
		const manifest = manifestOf(dir)
		/* a record two databases list, as one written before the refusal above could be */
		fs.mkdirSync(path.dirname(manifest), { recursive: true })
		fs.writeFileSync(manifest, json)
		const both = { aux: ["src/shared/manifest.gen.json"], core: ["src/shared/manifest.gen.json"] }
		fs.writeFileSync(
			path.join(dir, ".comb.codegen.gen.json"),
			JSON.stringify({ _generated: "comb checksum:x", databases: both }),
		)
		commitRuns(new Map(), [run(dir)], { recordDir: dir })
		expect(fs.existsSync(manifest)).toBe(true)
		expect(record(dir).databases).toEqual({ aux: ["src/shared/manifest.gen.json"], core: [] })
	})
})

/* the 0.12 review's F28 and F29: a stale file that would not go, and 0.9's record when it is no JSON */
describe("commitRuns: deleting what is stale (F28, F29)", () => {
	it("keeps a stale file in the record when it cannot be deleted, so a later run deletes it", () => {
		const dir = dirWith({})
		const gone = path.join(dir, "src/db/dtos/gone/db.core.gone.gen.ts")
		commitRuns(new Map([[gone, GENERATED]]), [run(dir, { wrote: [gone] })], { recordDir: dir })
		fs.chmodSync(path.dirname(gone), 0o555)
		try {
			expect(() => commitRuns(new Map(), [run(dir)], { recordDir: dir })).toThrow(/EACCES/)
			expect(record(dir).databases["core"]).toEqual(["src/db/dtos/gone/db.core.gone.gen.ts"])
		} finally {
			fs.chmodSync(path.dirname(gone), 0o755)
		}
		commitRuns(new Map(), [run(dir)], { recordDir: dir })
		expect(fs.existsSync(gone)).toBe(false)
	})

	it("names 0.9's record when it is no JSON, as it names the current one", () => {
		const dir = dirWith({ "src/db/.db.core.codegen.json": "<<<<<<< HEAD\n" })
		expect(() => commitRuns(new Map(), [run(dir)], { recordDir: dir })).toThrow(
			/^src\/db\/\.db\.core\.codegen\.json is not JSON \(a merge conflict\?\): delete it, and the next run removes nothing stale/,
		)
	})
})
