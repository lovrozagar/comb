/**
 * File system utilities for code generation
 */
import crypto from "node:crypto"
import fs from "node:fs"
import path from "node:path"

/** Ensure a directory exists, creating it recursively if needed */
export function ensureDir(dirPath: string): void {
	if (!fs.existsSync(dirPath)) {
		fs.mkdirSync(dirPath, { recursive: true })
	}
}

/* a UUID rather than random bytes as hex: a consumer build that also loads the Workers types sees
 * the bytes as a plain Uint8Array, whose toString takes no encoding */
const tmpPathFor = (filePath: string): string => `${filePath}.${crypto.randomUUID()}.tmp`

/**
 * The files a codegen run writes, by path, held until every generator has run: one that fails
 * then leaves the output as it was (see commitStaged)
 */
export type Staged = Map<string, string>

/** `filePath` written atomically (tmp + rename), or staged when a run stages its writes */
function put(filePath: string, content: string, staged: Staged | undefined): void {
	if (staged !== undefined) {
		staged.set(filePath, content)
		return
	}
	ensureDir(path.dirname(filePath))
	const tmpPath = tmpPathFor(filePath)
	fs.writeFileSync(tmpPath, content)
	fs.renameSync(tmpPath, filePath)
}

/** A file's content as the run sees it: what it staged, else what is on disk */
export function readStaged(filePath: string, staged: Staged | undefined): string {
	return staged?.get(filePath) ?? fs.readFileSync(filePath, "utf-8")
}

/**
 * Write every staged file: each to a temporary file first, then all renamed into place, so the
 * output changes only once every file is written. A file already as staged is left alone.
 */
export function commitStaged(staged: Staged): void {
	const changed = [...staged].filter(
		([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, "utf-8") !== content,
	)
	const written: Array<readonly [string, string]> = []
	try {
		for (const [file, content] of changed) {
			ensureDir(path.dirname(file))
			const tmpPath = tmpPathFor(file)
			fs.writeFileSync(tmpPath, content)
			written.push([tmpPath, file])
		}
	} catch (error) {
		/* nothing is renamed yet: the output is as it was, and no temporary file stays behind (F29) */
		for (const [tmpPath] of written) fs.rmSync(tmpPath, { force: true })
		throw error
	}
	for (const [tmpPath, file] of written) fs.renameSync(tmpPath, file)
}

/** Atomically write JSON (tmp + rename), or stage it; a package.json comb updates keeps its other keys */
export function writeJsonAtomic(filePath: string, data: unknown, staged?: Staged): void {
	put(filePath, `${JSON.stringify(data, null, "\t")}\n`, staged)
}

/** Check if a file exists */
export function fileExists(filePath: string): boolean {
	return fs.existsSync(filePath)
}

/** Read file content as string */
export function readFile(filePath: string): string {
	return fs.readFileSync(filePath, "utf-8")
}

function contentHash(content: string): string {
	return crypto.createHash("sha256").update(content).digest("hex").slice(0, 12)
}

function buildHeader(hash: string, generator: string, ext: string): string {
	if (ext === ".sql") return `-- @generated by ${generator} — do not edit. checksum: ${hash}`
	if (ext === ".txt") return `# @generated by ${generator} — do not edit. checksum: ${hash}`
	return `/* @generated by ${generator} — do not edit. checksum: ${hash} */`
}

/**
 * Write a generated file with a checksum header.
 * Skips the write when the existing file is exactly what it would write (idempotent; a hand edit
 * under a matching header is put back), and refuses to overwrite a file that carries no
 * @generated header.
 * Returns true if the file was written, false if skipped.
 */
/** How a generated file is written: the generator its header names, and the run's staging, if any */
export type GenWrite = { generator: string; staged?: Staged | undefined }

export function writeGenFile(filePath: string, body: string, { generator, staged }: GenWrite): boolean {
	const normalized = body.replace(/\n*$/, "\n")
	const hash = contentHash(normalized)

	const ext = filePath.endsWith(".d.ts") ? ".d.ts" : path.extname(filePath)
	const header = buildHeader(hash, generator, ext)
	const fullContent = `${header}\n${normalized}`

	if (fs.existsSync(filePath)) {
		const existing = fs.readFileSync(filePath, "utf-8")
		const firstLine = existing.split("\n", 1).join("")
		/* a file without comb's header is someone's own code, or another tool's, at the output path (F17) */
		if (existing !== "" && !COMB_HEADER.test(firstLine)) {
			throw new Error(
				`refusing to overwrite ${filePath}: it has no "@generated by comb" header, so comb did not write it`,
			)
		}
		/* a staging run records every file it produces, unchanged ones too: they are not stale */
		if (existing === fullContent && staged === undefined) return false
	}

	put(filePath, fullContent, staged)
	return true
}

/* the header comb writes: its name, then the dash, so another tool whose name starts with comb is not it (F27) */
const COMB_HEADER = /@generated by comb —/

/** Whether `text`, a JSON file's content, carries comb's `_generated` marker, not another tool's (F17) */
function hasGeneratedMarker(text: string): boolean {
	try {
		const marker = (JSON.parse(text) as Record<string, unknown> | null)?.["_generated"]
		return typeof marker === "string" && marker.startsWith("comb ")
	} catch {
		// reason: text that is not JSON is not a file comb wrote; the caller refuses it
		return false
	}
}

/**
 * Write a generated JSON file with a `_generated` metadata key.
 * Skips the write when the existing file is exactly what it would write, and refuses to
 * overwrite a file that carries no `_generated` key.
 * Returns true if the file was written, false if skipped.
 */
export function writeGenJsonFile(filePath: string, data: unknown, { generator, staged }: GenWrite): boolean {
	const marker = `${generator} checksum:${contentHash(JSON.stringify(data, null, 2))}`
	const content = `${JSON.stringify({ _generated: marker, ...(data as Record<string, unknown>) }, null, 2)}\n`

	const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf-8") : ""
	/* like writeGenFile: a file without the marker is someone's own data at the output path */
	if (existing !== "" && !hasGeneratedMarker(existing)) {
		throw new Error(`refusing to overwrite ${filePath}: it has no comb _generated key, so comb did not write it`)
	}
	if (existing === content && staged === undefined) return false

	put(filePath, content, staged)
	return true
}

/** Whether `text` is a file comb wrote: an @generated header, or a JSON _generated key */
export function isGeneratedContent(text: string): boolean {
	return COMB_HEADER.test(text.split("\n", 1).join("")) || hasGeneratedMarker(text)
}
