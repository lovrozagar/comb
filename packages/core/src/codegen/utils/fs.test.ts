import { fixtureRoot } from "../__fixtures__/temp.ts"
import fs from "node:fs"
import path from "node:path"
import { afterEach, beforeEach, describe, expect, it } from "vitest"
import {
	commitStaged,
	ensureDir,
	fileExists,
	isGeneratedContent,
	readFile,
	writeGenFile,
	writeGenJsonFile,
	writeJsonAtomic,
} from "./fs.ts"

let tmpDir: string

beforeEach(() => {
	tmpDir = fs.mkdtempSync(path.join(fixtureRoot(), "comb-fs-test-"))
})

afterEach(() => {
	fs.rmSync(tmpDir, { force: true, recursive: true })
})

describe("codegen/utils/fs: ensureDir", () => {
	it("creates nested directories", () => {
		const nested = path.join(tmpDir, "a", "b", "c")
		ensureDir(nested)
		expect(fs.existsSync(nested)).toBe(true)
	})

	it("does not throw if already exists", () => {
		ensureDir(tmpDir)
		expect(fs.existsSync(tmpDir)).toBe(true)
	})
})

describe("codegen/utils/fs: writeJsonAtomic", () => {
	it("writes formatted JSON with trailing newline", () => {
		const fp = path.join(tmpDir, "data.json")
		writeJsonAtomic(fp, { a: 1, b: "two" })
		const content = fs.readFileSync(fp, "utf-8")
		expect(content).toBe('{\n\t"a": 1,\n\t"b": "two"\n}\n')
	})
})

describe("codegen/utils/fs: fileExists and readFile", () => {
	it("returns true for existing file", () => {
		const fp = path.join(tmpDir, "exists.txt")
		fs.writeFileSync(fp, "")
		expect(fileExists(fp)).toBe(true)
	})

	it("returns false for missing file", () => {
		expect(fileExists(path.join(tmpDir, "nope.txt"))).toBe(false)
	})

	it("reads file content", () => {
		const fp = path.join(tmpDir, "read.txt")
		fs.writeFileSync(fp, "hello world")
		expect(readFile(fp)).toBe("hello world")
	})
})

describe("codegen/utils/fs: writeGenFile headers", () => {
	it("writes .ts file with checksum header", () => {
		const fp = path.join(tmpDir, "out.gen.ts")
		writeGenFile(fp, "export const x = 1\n", { generator: "comb" })
		const content = fs.readFileSync(fp, "utf-8")
		expect(content).toMatch(/^\/\* @generated by comb — do not edit\. checksum: [0-9a-f]{12} \*\/\n/)
		expect(content).toContain("export const x = 1\n")
	})

	it("writes .sql file with SQL comment header", () => {
		const fp = path.join(tmpDir, "schema.gen.sql")
		writeGenFile(fp, "CREATE TABLE t (id INTEGER);\n", { generator: "comb" })
		const content = fs.readFileSync(fp, "utf-8")
		expect(content).toMatch(/^-- @generated by comb — do not edit\. checksum: [0-9a-f]{12}\n/)
	})

	it("writes .txt file with hash comment header", () => {
		const fp = path.join(tmpDir, "notes.gen.txt")
		writeGenFile(fp, "hello\n", { generator: "comb" })
		const content = fs.readFileSync(fp, "utf-8")
		expect(content).toMatch(/^# @generated by comb — do not edit\. checksum: [0-9a-f]{12}\n/)
	})

	it("normalizes trailing newlines", () => {
		const fp = path.join(tmpDir, "trail.gen.ts")
		writeGenFile(fp, "const a = 1\n\n\n", { generator: "comb" })
		const content = fs.readFileSync(fp, "utf-8")
		expect(content).toMatch(/const a = 1\n$/)
	})
})

describe("codegen/utils/fs: writeGenFile rewrites", () => {
	it("skips write when checksum matches existing file", () => {
		const fp = path.join(tmpDir, "skip.gen.ts")
		writeGenFile(fp, "const a = 1\n", { generator: "comb" })
		const stat1 = fs.statSync(fp).mtimeMs

		/* small delay so mtime would differ if rewritten */
		const wrote = writeGenFile(fp, "const a = 1\n", { generator: "comb" })
		expect(wrote).toBe(false)
		expect(fs.statSync(fp).mtimeMs).toBe(stat1)
	})

	it("rewrites when content differs from existing file", () => {
		const fp = path.join(tmpDir, "change.gen.ts")
		writeGenFile(fp, "const a = 1\n", { generator: "comb" })
		const wrote = writeGenFile(fp, "const a = 2\n", { generator: "comb" })
		expect(wrote).toBe(true)
		expect(fs.readFileSync(fp, "utf-8")).toContain("const a = 2")
	})

	it("restores a hand edit below the header, whose checksum still matches (G-S1)", () => {
		const fp = path.join(tmpDir, "edited.ts")
		writeGenFile(fp, "export const x = 1", { generator: "comb" })
		fs.writeFileSync(fp, fs.readFileSync(fp, "utf-8").replace("x = 1", "x = 2"))
		expect(writeGenFile(fp, "export const x = 1", { generator: "comb" })).toBe(true)
		expect(fs.readFileSync(fp, "utf-8")).toContain("export const x = 1")
		expect(writeGenFile(fp, "export const x = 1", { generator: "comb" })).toBe(false)
	})

	it("creates parent directories if missing", () => {
		const fp = path.join(tmpDir, "deep", "nested", "out.gen.ts")
		writeGenFile(fp, "export {}\n", { generator: "comb" })
		expect(fs.existsSync(fp)).toBe(true)
	})
})

describe("codegen/utils/fs: writeGenJsonFile", () => {
	it("writes JSON with _generated key", () => {
		const fp = path.join(tmpDir, "data.gen.json")
		writeGenJsonFile(fp, { count: 5, name: "test" }, { generator: "comb" })
		const content = JSON.parse(fs.readFileSync(fp, "utf-8")) as Record<string, unknown>
		expect(content._generated).toMatch(/^comb checksum:[0-9a-f]{12}$/)
		expect(content.name).toBe("test")
		expect(content.count).toBe(5)
	})

	it("skips write when checksum matches", () => {
		const fp = path.join(tmpDir, "same.gen.json")
		writeGenJsonFile(fp, { a: 1 }, { generator: "comb" })
		const wrote = writeGenJsonFile(fp, { a: 1 }, { generator: "comb" })
		expect(wrote).toBe(false)
	})

	it("restores a hand edit to a file whose marker still matches (G-S1)", () => {
		const fp = path.join(tmpDir, "edited.json")
		writeGenJsonFile(fp, { a: 1 }, { generator: "comb" })
		fs.writeFileSync(fp, fs.readFileSync(fp, "utf-8").replace('"a": 1', '"a": 2'))
		expect(writeGenJsonFile(fp, { a: 1 }, { generator: "comb" })).toBe(true)
		expect((JSON.parse(fs.readFileSync(fp, "utf-8")) as { a: number }).a).toBe(1)
		expect(writeGenJsonFile(fp, { a: 1 }, { generator: "comb" })).toBe(false)
	})

	it("rewrites when data changes", () => {
		const fp = path.join(tmpDir, "diff.gen.json")
		writeGenJsonFile(fp, { a: 1 }, { generator: "comb" })
		const wrote = writeGenJsonFile(fp, { a: 2 }, { generator: "comb" })
		expect(wrote).toBe(true)
		const content = JSON.parse(fs.readFileSync(fp, "utf-8")) as Record<string, unknown>
		expect(content.a).toBe(2)
	})
})

describe("writeGenFile: files it did not write (S-13)", () => {
	it("refuses to overwrite a file without the @generated header, and leaves it as it was", () => {
		const file = path.join(tmpDir, "constraints.gen.ts")
		fs.writeFileSync(file, "// hand-written\nexport const keep = 1\n")
		expect(() => writeGenFile(file, "export const x = 1\n", { generator: "comb" })).toThrow(
			`refusing to overwrite ${file}: it has no "@generated by comb" header, so comb did not write it`,
		)
		expect(fs.readFileSync(file, "utf8")).toBe("// hand-written\nexport const keep = 1\n")
	})

	it("writes a declaration file under the TypeScript header", () => {
		const file = path.join(tmpDir, "types.gen.d.ts")
		writeGenFile(file, "export type X = 1\n", { generator: "comb" })
		expect(fs.readFileSync(file, "utf8")).toMatch(/^\/\* @generated by comb/)
	})

	it("overwrites a file it generated before, and an empty one", () => {
		const file = path.join(tmpDir, "a.gen.ts")
		writeGenFile(file, "export const x = 1\n", { generator: "comb" })
		expect(writeGenFile(file, "export const x = 2\n", { generator: "comb" })).toBe(true)
		fs.writeFileSync(path.join(tmpDir, "empty.gen.ts"), "")
		expect(writeGenFile(path.join(tmpDir, "empty.gen.ts"), "export const y = 1\n", { generator: "comb" })).toBe(true)
	})
})

describe("writeGenJsonFile: files it did not write (S-13)", () => {
	it.each([
		["JSON without a _generated key", '{ "mine": true }\n'],
		["a file that is not JSON", "not json at all\n"],
	])("refuses to overwrite %s, and leaves it as it was", (_label, original) => {
		const file = path.join(tmpDir, "manifest.gen.json")
		fs.writeFileSync(file, original)
		expect(() => writeGenJsonFile(file, { v: 1 }, { generator: "comb" })).toThrow(
			`refusing to overwrite ${file}: it has no comb _generated key, so comb did not write it`,
		)
		expect(fs.readFileSync(file, "utf8")).toBe(original)
	})

	it("overwrites a file it generated before, and an empty one", () => {
		const file = path.join(tmpDir, "a.gen.json")
		writeGenJsonFile(file, { v: 1 }, { generator: "comb" })
		expect(writeGenJsonFile(file, { v: 2 }, { generator: "comb" })).toBe(true)
		fs.writeFileSync(path.join(tmpDir, "empty.gen.json"), "")
		expect(writeGenJsonFile(path.join(tmpDir, "empty.gen.json"), { v: 1 }, { generator: "comb" })).toBe(true)
	})
})

describe("the overwrite guard takes comb's own header alone (F17)", () => {
	it("refuses a file another tool generated, as it refuses one with no header", () => {
		const dir = fs.mkdtempSync(path.join(fixtureRoot(), "comb-guard-"))
		try {
			const code = path.join(dir, "rows.gen.ts")
			fs.writeFileSync(code, "// @generated by other-tool\nexport const x = 1\n")
			expect(() => writeGenFile(code, "export {}", { generator: "comb" })).toThrow(
				/refusing to overwrite .*rows\.gen\.ts/,
			)
			const json = path.join(dir, "manifest.gen.json")
			fs.writeFileSync(json, JSON.stringify({ _generated: "other-tool checksum:1" }))
			expect(() => writeGenJsonFile(json, {}, { generator: "comb" })).toThrow(
				/refusing to overwrite .*manifest\.gen\.json/,
			)
			expect(isGeneratedContent(fs.readFileSync(json, "utf8"))).toBe(false)
			fs.writeFileSync(json, JSON.stringify({ _generated: "comb checksum:1" }))
			expect(() => writeGenJsonFile(json, {}, { generator: "comb" })).not.toThrow()
		} finally {
			fs.rmSync(dir, { force: true, recursive: true })
		}
	})
})

describe("commitStaged on a write that fails (F29)", () => {
	it("removes every temporary file it wrote, changes no output, and rethrows", () => {
		const dir = fs.mkdtempSync(path.join(fixtureRoot(), "comb-commit-"))
		const locked = path.join(dir, "locked")
		fs.mkdirSync(locked)
		fs.chmodSync(locked, 0o500)
		try {
			const staged = new Map([
				[path.join(dir, "a.gen.ts"), "a"],
				[path.join(locked, "b.gen.ts"), "b"],
			])
			expect(() => commitStaged(staged)).toThrow(/EACCES/)
			expect(fs.readdirSync(dir).sort()).toEqual(["locked"])
		} finally {
			fs.chmodSync(locked, 0o700)
			fs.rmSync(dir, { force: true, recursive: true })
		}
	})
})

