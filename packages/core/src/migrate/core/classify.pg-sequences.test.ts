/**
 * M82 of the 0.13.0 round: a sequence reset is cautious however it is spelled, read from the parse
 * tree: an ALTER SEQUENCE with a RESTART option anywhere in its list, and an identity column's SET
 * or ADD with RESTART, which reset the column's sequence so the next insert may reuse an id.
 */
import { describe, expect, it } from "vitest"
import { classifyMigration } from "./classify.ts"
import { extractSchema } from "./schema.ts"

const HISTORY = "CREATE SEQUENCE s; CREATE TABLE users (id int GENERATED BY DEFAULT AS IDENTITY, name text);"

/** `later`'s rating after HISTORY, both read as Postgres */
function rate(later: string) {
	const before = extractSchema(HISTORY, undefined, "postgres")
	return classifyMigration(later, { before, dialect: "postgres" })
}

describe("a sequence reset, in every spelling (M82)", () => {
	it("is cautious for ALTER SEQUENCE with RESTART anywhere in its options", () => {
		for (const later of [
			"ALTER SEQUENCE s MINVALUE 1 RESTART;",
			"ALTER SEQUENCE s RESTART WITH 5;",
			"ALTER SEQUENCE s RESTART;",
		]) {
			const rated = rate(later)
			expect([later, rated.safety]).toEqual([later, "cautious"])
			expect(rated.cautiousStatements.join(" ")).toContain("restarts a sequence, as a RESTART does")
		}
	})

	it("is cautious for an identity column's RESTART, set or added, and leaves another identity option safe", () => {
		for (const later of [
			"ALTER TABLE users ALTER COLUMN id RESTART WITH 1;",
			"ALTER TABLE users ALTER COLUMN id SET INCREMENT BY 2 RESTART;",
			"ALTER TABLE users ALTER COLUMN name ADD GENERATED ALWAYS AS IDENTITY (RESTART 5);",
		])
			expect([later, rate(later).safety]).toEqual([later, "cautious"])
		expect(rate("ALTER TABLE users ALTER COLUMN id SET INCREMENT BY 2;").safety).toBe("safe")
		expect(rate("ALTER TABLE users ALTER COLUMN name ADD GENERATED ALWAYS AS IDENTITY;").safety).toBe("safe")
	})

	it("leaves the other resets as they were rated: TRUNCATE … RESTART IDENTITY unsafe, setval cautious", () => {
		expect(rate("TRUNCATE users RESTART IDENTITY;").safety).toBe("unsafe")
		const set = rate("SELECT setval('s', 1);")
		expect(set.safety).toBe("cautious")
		expect(set.cautiousStatements.join(" ")).toContain("sets a sequence, as a RESTART does")
	})
})
