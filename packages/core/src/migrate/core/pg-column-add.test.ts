/**
 * P6 of the 0.14.1 review: an added column's type and inline constraints, read as the matching
 * ALTER TABLE commands are. A serial, an identity or a stored generated column fills every row, so
 * Postgres rewrites the table; an inline check or reference scans it; an inline primary key fails
 * on a table with rows unless each row gets its own value.
 */
import { beforeAll, describe, expect, it } from "vitest"
import { classifyMigration } from "./classify.ts"
import { extractSchema } from "./schema.ts"
import { historyFacts } from "./pg-history.ts"
import { ddlFindings, REWRITES } from "./pg-ddl.ts"
import type { Node } from "./pg-nodes.ts"
import { loadPostgresParser, postgresParser } from "./pg-parser.ts"

beforeAll(() => loadPostgresParser())

/** The DDL findings of `sql`'s one statement */
function rated(sql: string) {
	const [stmt] = postgresParser().parseSync(sql).stmts as Array<{ stmt: Node }>
	const [type, node] = Object.entries((stmt as { stmt: Node }).stmt)[0] as [string, Node]
	return ddlFindings(type, node, historyFacts(undefined, "public"))
}

const REWRITE = { level: "lock", note: REWRITES }

/** `later`'s lock warnings after a table t and `history`, read as Postgres */
const warnedAfter = (history: string, later: string) =>
	classifyMigration(later, {
		before: extractSchema(`CREATE TABLE t (id int PRIMARY KEY);${history}`, undefined, "postgres"),
		dialect: "postgres",
	}).lockWarnings

describe("an added column that fills every row (P6)", () => {
	it("warns of the rewrite for a serial, an identity and a stored generated column", () => {
		for (const sql of [
			"ALTER TABLE t ADD COLUMN n serial",
			"ALTER TABLE t ADD COLUMN n bigserial NOT NULL",
			"ALTER TABLE t ADD COLUMN n smallserial",
			"ALTER TABLE t ADD COLUMN n pg_catalog.serial8",
			"ALTER TABLE t ADD COLUMN n int GENERATED ALWAYS AS IDENTITY",
			"ALTER TABLE t ADD COLUMN n int NOT NULL GENERATED BY DEFAULT AS IDENTITY",
			"ALTER TABLE t ADD COLUMN n int GENERATED ALWAYS AS (1) STORED",
		])
			expect(rated(sql), sql).toEqual([REWRITE])
	})

	it("warns of none for a plain type or a constant default", () => {
		for (const sql of ["ALTER TABLE t ADD COLUMN n int", "ALTER TABLE t ADD COLUMN n int NOT NULL DEFAULT 0"])
			expect(rated(sql), sql).toEqual([])
	})
})

describe("an added column's inline constraints (P6)", () => {
	it("warns of the scan of an inline check or reference, as ADD CONSTRAINT does", () => {
		for (const sql of [
			"ALTER TABLE t ADD COLUMN n int CHECK (n > 0)",
			"ALTER TABLE t ADD COLUMN n int REFERENCES u (id)",
			"ALTER TABLE t ADD COLUMN n int CONSTRAINT f REFERENCES u",
		])
			expect(rated(sql), sql).toEqual([REWRITE])
	})

	it("rates an inline primary key unsafe, unless each row gets its own value", () => {
		for (const sql of [
			"ALTER TABLE t ADD COLUMN n int PRIMARY KEY",
			"ALTER TABLE t ADD COLUMN n int PRIMARY KEY DEFAULT 0",
			"ALTER TABLE t ADD COLUMN n text CONSTRAINT k PRIMARY KEY",
		])
			expect(
				rated(sql)?.map((finding) => finding.level),
				sql,
			).toContain("unsafe")
		for (const sql of [
			"ALTER TABLE t ADD COLUMN n serial PRIMARY KEY",
			"ALTER TABLE t ADD COLUMN n int PRIMARY KEY GENERATED ALWAYS AS IDENTITY",
			"ALTER TABLE t ADD COLUMN n uuid PRIMARY KEY DEFAULT gen_random_uuid()",
		])
			expect(
				rated(sql)?.map((finding) => finding.level),
				sql,
			).not.toContain("unsafe")
	})

	it("rates an inline unique nothing here: its index lock is the table's warning", () => {
		expect(rated("ALTER TABLE t ADD COLUMN n int UNIQUE")).toEqual([])
	})
})

/* r18 P2: a domain's default fills a column that has none of its own; an operator or a cast runs its function */
describe("an added column's default that comes through the history", () => {
	const T = "CREATE TABLE t (id int PRIMARY KEY);"
	const ratedAfter = (history: string, later: string) =>
		classifyMigration(later, { before: extractSchema(`${T}${history}`, undefined, "postgres"), dialect: "postgres" })

	it.each([
		["CREATE DOMAIN dv AS float8 DEFAULT random();", "ALTER TABLE t ADD COLUMN x dv;"],
		["CREATE DOMAIN dv AS float8 DEFAULT random();", "ALTER TABLE t ADD COLUMN x dv NOT NULL;"],
		["CREATE DOMAIN d0 AS float8 DEFAULT random(); CREATE DOMAIN dv AS d0;", "ALTER TABLE t ADD COLUMN x dv;"],
		["CREATE DOMAIN dv AS float8; ALTER DOMAIN dv SET DEFAULT random();", "ALTER TABLE t ADD COLUMN x dv;"],
	])("after %j, rates %j safe and warns of the rewrite the domain's default makes", (history, later) => {
		const rating = ratedAfter(history, later)
		expect([rating.safety, rating.lockWarnings]).toEqual(["safe", [`${later.slice(0, -1)} (${REWRITES})`]])
	})

	it("reads a domain's constant default as filling a NOT NULL column, and a dropped one as none", () => {
		const constant = ratedAfter("CREATE DOMAIN dn AS int DEFAULT 0;", "ALTER TABLE t ADD COLUMN x dn NOT NULL;")
		expect([constant.safety, constant.lockWarnings]).toEqual(["safe", []])
		const dropped = ratedAfter(
			"CREATE DOMAIN dn AS int DEFAULT 0; ALTER DOMAIN dn DROP DEFAULT;",
			"ALTER TABLE t ADD COLUMN x dn NOT NULL;",
		)
		expect(dropped.safety).toBe("unsafe")
		const own = ratedAfter("CREATE DOMAIN dv AS float8 DEFAULT random();", "ALTER TABLE t ADD COLUMN x dv DEFAULT 1;")
		expect(own.lockWarnings).toEqual([])
	})

	it.each([
		[
			"CREATE FUNCTION vadd(int, int) RETURNS int LANGUAGE plpgsql VOLATILE AS 'BEGIN RETURN $1 + $2; END'; CREATE OPERATOR @+@ (LEFTARG = int, RIGHTARG = int, FUNCTION = vadd);",
			"ALTER TABLE t ADD COLUMN x int DEFAULT 1 @+@ 2;",
		],
		[
			"CREATE TYPE mt AS (a int); CREATE FUNCTION vc(int) RETURNS mt LANGUAGE sql VOLATILE AS 'SELECT ROW($1)::mt'; CREATE CAST (int AS mt) WITH FUNCTION vc(int);",
			"ALTER TABLE t ADD COLUMN x mt DEFAULT 1::mt;",
		],
	])("after %j, warns of the rewrite in %j, the function behind it being volatile", (history, later) => {
		expect(ratedAfter(history, later).lockWarnings.join("\n")).toContain(REWRITES)
	})

	it("warns of nothing for an operator whose function says IMMUTABLE", () => {
		const history =
			"CREATE FUNCTION iadd(int, int) RETURNS int LANGUAGE sql IMMUTABLE AS 'SELECT $1 + $2'; CREATE OPERATOR @+@ (LEFTARG = int, RIGHTARG = int, FUNCTION = iadd);"
		expect(ratedAfter(history, "ALTER TABLE t ADD COLUMN x int DEFAULT 1 @+@ 2;").lockWarnings).toEqual([])
	})
})

/* r18 P15: a default that calls only IMMUTABLE or STABLE built-ins is evaluated once and rewrites nothing */
describe("an added column's default of built-ins Postgres 17 declares steady", () => {
	it.each([
		"ALTER TABLE t ADD COLUMN x timestamp DEFAULT timezone('utc'::text, now())",
		"ALTER TABLE t ADD COLUMN x timestamp DEFAULT (now() AT TIME ZONE 'utc')",
		"ALTER TABLE t ADD COLUMN x timestamptz DEFAULT to_timestamp(0)",
		"ALTER TABLE t ADD COLUMN x int DEFAULT coalesce(greatest(1, 2), 3)",
		"ALTER TABLE t ADD COLUMN x text DEFAULT pg_catalog.upper('a')",
	])("warns of no rewrite for %j", (sql) => {
		expect(rated(sql)).toEqual([])
	})

	it.each([
		"ALTER TABLE t ADD COLUMN x int DEFAULT (random() * 10)::int",
		"ALTER TABLE t ADD COLUMN x timestamptz DEFAULT clock_timestamp()",
		"ALTER TABLE t ADD COLUMN x int DEFAULT public.upper('a')",
		"ALTER TABLE t ADD COLUMN x int DEFAULT no_such_builtin()",
	])("warns of the rewrite for %j", (sql) => {
		expect(rated(sql)).toEqual([REWRITE])
	})
})

/*
 * P3 and P10 of r19: a domain's constraints and its default, followed through its chain, ALTER DOMAIN,
 * RENAME, SET SCHEMA and DROP, as Postgres 17 adds a column of it to a table with a row (probed by
 * .tmp/grunt/p18/runs/c457d3b-probe-p3-20261101T165229Z.log): a NOT NULL with nothing to fill it fails,
 * and any constraint, or a volatile default, rewrites the table
 */
describe("an added column of a domain, after the history that shaped the domain (P3, P10 of r19)", () => {
	const T = "CREATE TABLE t (id int PRIMARY KEY);"
	/* a NOT NULL is a constraint Postgres checks each row against, as a CHECK is: the rewrite warning stands beside it */
	const FAILS = ["unsafe", true] as const
	const REWRITTEN = ["safe", true] as const
	const NEITHER = ["safe", false] as const
	it.each([
		["CREATE DOMAIN d AS int NOT NULL;", "d", FAILS],
		["CREATE DOMAIN d AS int; ALTER DOMAIN d SET NOT NULL;", "d", FAILS],
		["CREATE DOMAIN d0 AS int NOT NULL; CREATE DOMAIN d AS d0;", "d", FAILS],
		["CREATE DOMAIN d0 AS int; CREATE DOMAIN d AS d0; ALTER DOMAIN d0 SET NOT NULL;", "d", FAILS],
		["CREATE DOMAIN d AS int CHECK (VALUE > 0);", "d", REWRITTEN],
		["CREATE DOMAIN d AS int; ALTER DOMAIN d ADD CHECK (VALUE > 0);", "d", REWRITTEN],
		["CREATE DOMAIN d0 AS int CHECK (VALUE > 0); CREATE DOMAIN d AS d0;", "d", REWRITTEN],
		["CREATE DOMAIN d AS int NOT NULL DEFAULT 0;", "d", REWRITTEN],
		["CREATE DOMAIN d AS int DEFAULT 0;", "d", NEITHER],
		["CREATE DOMAIN d AS int CONSTRAINT nn NOT NULL; ALTER DOMAIN d DROP CONSTRAINT nn;", "d", NEITHER],
		["CREATE DOMAIN d AS int; ALTER DOMAIN d SET NOT NULL; ALTER DOMAIN d DROP NOT NULL;", "d", NEITHER],
		["CREATE DOMAIN d AS int CHECK (VALUE > 0); ALTER DOMAIN d DROP CONSTRAINT d_check;", "d", NEITHER],
		[
			"CREATE DOMAIN d AS int CHECK (VALUE > 0); ALTER DOMAIN d RENAME CONSTRAINT d_check TO c; ALTER DOMAIN d DROP CONSTRAINT c;",
			"d",
			NEITHER,
		],
		[
			"CREATE DOMAIN d AS int CHECK (VALUE > 0) CHECK (VALUE < 9); ALTER DOMAIN d DROP CONSTRAINT d_check;",
			"d",
			REWRITTEN,
		],
		["CREATE DOMAIN d AS int NOT NULL; ALTER DOMAIN d DROP CONSTRAINT d_not_null;", "d", NEITHER],
		["CREATE DOMAIN dv AS float8 DEFAULT random(); ALTER DOMAIN dv RENAME TO d;", "d", REWRITTEN],
		["CREATE SCHEMA s; CREATE DOMAIN d AS float8 DEFAULT random(); ALTER DOMAIN d SET SCHEMA s;", "s.d", REWRITTEN],
		["CREATE DOMAIN d AS float8 DEFAULT random(); DROP DOMAIN d; CREATE DOMAIN d AS float8;", "d", NEITHER],
		["CREATE DOMAIN d AS float8 DEFAULT random(); DROP TYPE d; CREATE DOMAIN d AS float8;", "d", NEITHER],
		["CREATE DOMAIN d AS int NOT NULL; ALTER DOMAIN d RENAME TO e; CREATE DOMAIN d AS int;", "d", NEITHER],
		["CREATE DOMAIN d AS int NOT NULL; ALTER DOMAIN d RENAME TO e;", "e", FAILS],
	] as const)("after %j, rates adding a column of %s as Postgres runs it", (history, type, [safety, rewrites]) => {
		const later = `ALTER TABLE t ADD COLUMN x ${type};`
		const rating = classifyMigration(later, {
			before: extractSchema(`${T}${history}`, undefined, "postgres"),
			dialect: "postgres",
		})
		expect([rating.safety, rating.lockWarnings.some((warning) => warning.includes(REWRITES))]).toEqual([
			safety,
			rewrites,
		])
	})
})

/* the reviewer's ruling 1 on 4.1: a default can break the domain's CHECK on existing rows, which no empty dev shows */
describe("an added column of a domain with a CHECK, filled by a default", () => {
	it("says the default is checked against the domain's constraints on every existing row, and only where it has a CHECK", () => {
		expect(
			warnedAfter(
				"CREATE DOMAIN d0 AS int CHECK (VALUE > 0); CREATE DOMAIN d AS d0;",
				"ALTER TABLE t ADD COLUMN x d DEFAULT -1;",
			),
		).toEqual([
			`ALTER TABLE t ADD COLUMN x d DEFAULT -1 (${REWRITES}; Postgres checks the default against d's constraints on every existing row, and fails if any row's value breaks one)`,
		])
		expect(warnedAfter("CREATE DOMAIN d AS int NOT NULL;", "ALTER TABLE t ADD COLUMN x d DEFAULT 0;")).toEqual([
			`ALTER TABLE t ADD COLUMN x d DEFAULT 0 (${REWRITES})`,
		])
	})
})
