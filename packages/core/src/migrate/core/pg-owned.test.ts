/**
 * The columns a Postgres history leaves owning a sequence: serial and identity columns, a column a
 * sequence's OWNED BY names, kept through a retype and a rename and forgotten with a drop.
 */
import { beforeAll, describe, expect, it } from "vitest"
import { historyFacts } from "./pg-history.ts"
import { loadPostgresParser } from "./pg-parser.ts"
import { extractSchema } from "./schema.ts"

beforeAll(loadPostgresParser)

/** The columns of `table` that own a sequence after `history` */
const owners = (history: string, table = "t"): string[] =>
	[...(historyFacts(extractSchema(history, undefined, "postgres"), "public").columnTypes.get(table) ?? [])]
		.filter(([, type]) => type.owns === true)
		.map(([column]) => column)

// lookup-table: each history, with the columns of t it leaves owning a sequence
const OWNERS: ReadonlyArray<readonly [string, string[]]> = [
	["CREATE TABLE t (a serial, b bigserial, c smallserial, d serial8, e int, f text);", ["a", "b", "c", "d"]],
	["CREATE TABLE t (a int GENERATED ALWAYS AS IDENTITY, b int GENERATED BY DEFAULT AS IDENTITY, c int);", ["a", "b"]],
	/* serial is no type of a schema: a qualified name of it is some other type */
	["CREATE SCHEMA x;\nCREATE TYPE x.serial AS (n int);\nCREATE TABLE t (a x.serial);", []],
	["CREATE TABLE t (a int, b int);\nALTER TABLE t ALTER COLUMN b ADD GENERATED ALWAYS AS IDENTITY;", ["b"]],
	["CREATE TABLE t (a int);\nALTER TABLE t ADD COLUMN b int GENERATED ALWAYS AS IDENTITY;", ["b"]],
	["CREATE TABLE t (a int, b int);\nCREATE SEQUENCE s OWNED BY t.b;", ["b"]],
	["CREATE TABLE t (a int, b int);\nCREATE SEQUENCE s;\nALTER SEQUENCE s OWNED BY public.t.a;", ["a"]],
	["CREATE TABLE t (a int);\nCREATE SEQUENCE s OWNED BY NONE;\nCREATE SEQUENCE s2 INCREMENT 2;", []],
	/* an OWNED BY of a column the history does not show leaves it unknown, as a drop reads it */
	["CREATE TABLE t (a int);\nCREATE SEQUENCE s OWNED BY t.z;", []],
	["CREATE TABLE t (a serial);\nALTER TABLE t ALTER COLUMN a TYPE bigint;", ["a"]],
	["CREATE TABLE t (a serial);\nALTER TABLE t RENAME COLUMN a TO b;", ["b"]],
	["CREATE TABLE t (a serial, b int);\nALTER TABLE t DROP COLUMN a;", []],
	["CREATE TABLE t (a serial);\nDROP TABLE t;\nCREATE TABLE t (a int);", []],
]

describe("the columns a history leaves owning a sequence", () => {
	it.each(OWNERS)("%s leaves %j owning one", (history, columns) => {
		expect(owners(history)).toEqual(columns)
	})
})
