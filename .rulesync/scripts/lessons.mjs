#!/usr/bin/env node
/** Lessons: one committed file per repeat mistake under .rulesync/lessons/, plus a generated index. */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { canonicalPath, resolveRoots } from "./workspace-root.mjs";

export const LESSONS_DIR = ".rulesync/lessons";
export const INDEX_NAME = "INDEX.md";
export const MAX_LINES = 60;
export const MAX_EVIDENCE = 5;
export const DEFAULT_CAP = 10;
const BANNER = "<!-- Generated by lessons.mjs. Do not hand-edit. -->";
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const KEYS = ["name", "paths", "hits", "last-hit", "evidence"];
const SKIP_WALK = new Set([".git", "node_modules", ".tmp"]);
const USAGE =
  "usage: lessons.mjs match <file...> | hit <slug> --evidence <text> | rm <slug> | index | check";

function utcDate(d = new Date()) {
  return d.toISOString().slice(0, 10);
}

function toPosix(p) {
  return p.split(path.sep).join("/");
}

function lessonsDir(ws) {
  return path.join(ws, LESSONS_DIR);
}

function lessonPath(ws, slug) {
  return path.join(lessonsDir(ws), `${slug}.md`);
}

/** Glob to an anchored RegExp over repo-relative posix paths. `**` spans dirs; `*` and `?` stay in one segment. */
export function globToRegExp(glob) {
  let re = "";
  const g = String(glob);
  for (let i = 0; i < g.length; i++) {
    const c = g[i];
    if (c === "*" && g[i + 1] === "*") {
      if (g[i + 2] === "/") {
        re += "(?:.*/)?";
        i += 2;
      } else {
        re += ".*";
        i += 1;
      }
    } else if (c === "*") re += "[^/]*";
    else if (c === "?") re += "[^/]";
    else re += c.replace(/[.+^${}()|[\]\\]/g, "\\$&");
  }
  return new RegExp(`^${re}$`);
}

function readFrontmatter(text) {
  const s = String(text).replace(/^﻿/, "");
  if (!s.startsWith("---\n")) return null;
  const end = s.indexOf("\n---\n", 4);
  if (end === -1) return null;
  const map = {};
  for (const line of s.slice(4, end).split("\n")) {
    const m = line.match(/^([a-z-]+):\s*(.*)$/);
    if (m) map[m[1]] = m[2].trim();
  }
  return { map, body: s.slice(end + 5) };
}

function jsonList(raw) {
  try {
    const v = JSON.parse(raw);
    return Array.isArray(v) && v.every((x) => typeof x === "string") ? v : null;
  } catch {
    return null;
  }
}

/** Split the body into title, summary, and the Mistake/Fix sections. */
function readBody(body) {
  const errors = [];
  const lines = String(body).split("\n");
  const h1 = lines.findIndex((l) => /^# \S/.test(l));
  if (h1 === -1) errors.push("start the body with a # title line");
  const title = h1 === -1 ? "" : lines[h1].slice(2).trim();
  const summary = (lines.slice(h1 + 1).find((l) => l.trim() && !l.startsWith("#")) || "").trim();
  const firstH2 = lines.findIndex((l) => l.startsWith("## "));
  if (!summary || (firstH2 !== -1 && lines.indexOf(summary) > firstH2)) {
    errors.push("put a one-line summary under the # title");
  }
  const h2 = lines.map((l, i) => ({ l, i })).filter(({ l }) => l.startsWith("## "));
  const names = h2.map(({ l }) => l.slice(3).trim());
  const sections = {};
  h2.forEach(({ i }, k) => {
    sections[names[k]] = lines.slice(i + 1, k + 1 < h2.length ? h2[k + 1].i : lines.length).join("\n").trim();
  });
  for (const need of ["Mistake", "Fix"]) {
    if (!names.includes(need)) errors.push(`missing ## ${need}`);
    else if (!sections[need]) errors.push(`## ${need} is empty`);
  }
  if (names.length !== 2 || names[0] !== "Mistake" || names[1] !== "Fix") {
    errors.push("use only ## Mistake then ## Fix as section headings");
  }
  return { title, summary, mistake: sections.Mistake || "", fix: sections.Fix || "", errors };
}

/** Parse a lesson file. `defaults` fills missing hits and last-hit (a first write). */
export function parseLesson(text, { defaults } = {}) {
  const fm = readFrontmatter(text);
  if (!fm) return { ok: false, errors: ["start with --- frontmatter (name, paths, hits, last-hit, evidence)"] };
  const errors = [];
  const map = { ...(defaults || {}), ...fm.map };
  for (const k of Object.keys(fm.map)) if (!KEYS.includes(k)) errors.push(`unknown frontmatter key: ${k}`);
  const paths = jsonList(map.paths ?? "");
  if (!paths || !paths.length) errors.push('paths must list at least one glob, e.g. paths: ["src/**"]');
  const evidence = jsonList(map.evidence ?? "[]");
  if (!evidence) errors.push('evidence must be a JSON list, e.g. evidence: ["plan 16"]');
  const hits = Number(map.hits);
  if (!Number.isInteger(hits) || hits < 1) errors.push("hits must be a whole number ≥ 1");
  if (!DATE_RE.test(String(map["last-hit"] ?? ""))) errors.push("last-hit must be YYYY-MM-DD");
  if (!SLUG_RE.test(String(map.name ?? ""))) errors.push("name must be the lowercase-hyphen slug of the filename");
  const body = readBody(fm.body);
  errors.push(...body.errors);
  if (errors.length) return { ok: false, errors };
  return {
    ok: true,
    lesson: {
      name: map.name,
      paths,
      hits,
      lastHit: map["last-hit"],
      evidence,
      title: body.title,
      summary: body.summary,
      mistake: body.mistake,
      fix: body.fix,
    },
  };
}

export function renderLesson(l) {
  return `---
name: ${l.name}
paths: ${JSON.stringify(l.paths)}
hits: ${l.hits}
last-hit: ${l.lastHit}
evidence: ${JSON.stringify(l.evidence)}
---

# ${l.title}

${l.summary}

## Mistake
${l.mistake}

## Fix
${l.fix}
`;
}

/** Repo-relative files: tracked and untracked-but-not-ignored in git, else a walk. */
export function repoFiles(ws) {
  const git = spawnSync("git", ["ls-files", "-co", "--exclude-standard"], { cwd: ws, encoding: "utf8" });
  if (git.status === 0) {
    return git.stdout.split("\n").filter(Boolean);
  }
  const out = [];
  const walk = (dir) => {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      if (SKIP_WALK.has(ent.name)) continue;
      const abs = path.join(dir, ent.name);
      if (ent.isDirectory()) walk(abs);
      else if (ent.isFile()) out.push(toPosix(path.relative(ws, abs)));
    }
  };
  walk(ws);
  return out;
}

export function validateLesson(filename, text, { files } = {}) {
  const errors = [];
  const lineCount = String(text).replace(/\n$/, "").split("\n").length;
  if (lineCount > MAX_LINES) {
    errors.push(`lesson is ${lineCount} lines; the cap is ${MAX_LINES} lines, so cut it or split the mistake`);
  }
  const parsed = parseLesson(text);
  if (!parsed.ok) return [...errors, ...parsed.errors];
  const slug = path.basename(filename, ".md");
  if (parsed.lesson.name !== slug) errors.push(`name ${parsed.lesson.name} must match the filename ${slug}`);
  if (files) {
    for (const glob of parsed.lesson.paths) {
      const re = globToRegExp(glob);
      if (!files.some((f) => re.test(f))) errors.push(`paths glob ${glob} matches no file; point it at code that exists`);
    }
  }
  return errors;
}

function lessonFiles(ws) {
  const dir = lessonsDir(ws);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((n) => n.endsWith(".md") && n !== INDEX_NAME)
    .sort();
}

function cell(s) {
  return String(s).replace(/\s+/g, " ").replace(/\|/g, "\\|");
}

/** `pending` maps a lesson filename to text the host is about to write. */
function indexRows(ws, pending = {}) {
  const rows = [];
  const names = [...new Set([...lessonFiles(ws), ...Object.keys(pending)])].sort();
  for (const name of names) {
    const text = pending[name] ?? fs.readFileSync(path.join(lessonsDir(ws), name), "utf8");
    const parsed = parseLesson(text);
    if (!parsed.ok) continue;
    const l = parsed.lesson;
    rows.push({ file: `${LESSONS_DIR}/${name}`, paths: l.paths, hits: l.hits, lastHit: l.lastHit, summary: l.summary });
  }
  return rows.sort((a, b) => b.hits - a.hits || a.file.localeCompare(b.file));
}

export function renderIndex(rows) {
  const body = rows.map(
    (r) => `| ${r.file} | ${cell(r.paths.join(", "))} | ${r.hits} | ${r.lastHit} | ${cell(r.summary)} |`,
  );
  return [
    BANNER,
    "",
    "# Lessons",
    "",
    "| lesson | paths | hits | last-hit | summary |",
    "| --- | --- | --- | --- | --- |",
    ...body,
    "",
  ].join("\n");
}

function parseIndex(text) {
  const rows = [];
  for (const line of String(text).split("\n")) {
    if (!line.startsWith(`| ${LESSONS_DIR}/`)) continue;
    const cells = line
      .slice(2, -2)
      .replace(/\\\|/g, "\u0000")
      .split(" | ")
      .map((c) => c.replace(/\u0000/g, "|"));
    if (cells.length !== 5) continue;
    rows.push({
      file: cells[0],
      paths: cells[1].split(", ").filter(Boolean),
      hits: Number(cells[2]),
      lastHit: cells[3],
      summary: cells[4],
    });
  }
  return rows;
}

/** Derived from the lesson files only, so any writer rerunning it converges; temp file then rename. */
export function writeIndex({ workspaceRoot, pending }) {
  const ws = workspaceRoot || resolveRoots().checkout;
  const dir = lessonsDir(ws);
  fs.mkdirSync(dir, { recursive: true });
  const text = renderIndex(indexRows(ws, pending));
  const dest = path.join(dir, INDEX_NAME);
  const tmp = `${dest}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, dest);
  return { ok: true, path: dest };
}

/** Index rows whose globs match any of `files`, by hits then name. Reads INDEX.md only. */
export function matchLessons({ workspaceRoot, files, cap = DEFAULT_CAP }) {
  const ws = canonicalPath(path.resolve(workspaceRoot || resolveRoots().checkout));
  let text;
  try {
    text = fs.readFileSync(path.join(lessonsDir(ws), INDEX_NAME), "utf8");
  } catch {
    return [];
  }
  const rel = (files || [])
    .map((f) => path.relative(ws, canonicalPath(path.resolve(ws, f))))
    .filter((r) => r && !r.startsWith("..") && !path.isAbsolute(r))
    .map(toPosix);
  if (!rel.length) return [];
  return parseIndex(text)
    .filter((row) => row.paths.some((g) => rel.some((f) => globToRegExp(g).test(f))))
    .sort((a, b) => b.hits - a.hits || a.file.localeCompare(b.file))
    .slice(0, cap);
}

function writeLesson(ws, slug, text) {
  fs.mkdirSync(lessonsDir(ws), { recursive: true });
  fs.writeFileSync(lessonPath(ws, slug), text);
  writeIndex({ workspaceRoot: ws });
}

/**
 * A Write of `.rulesync/lessons/{slug}.md`: fill defaults, render canonical, validate, and reindex with
 * the pending text. The host writes the lesson: a write here first makes Claude Code refuse the Write.
 */
export function persistLesson({ workspaceRoot, filePath, content, today = utcDate() }) {
  const ws = workspaceRoot || resolveRoots().checkout;
  const abs = path.resolve(ws, filePath);
  const name = path.basename(abs);
  if (path.dirname(abs) !== lessonsDir(ws) || name === INDEX_NAME || !name.endsWith(".md")) {
    return { ok: false, error: `write lessons as ${LESSONS_DIR}/{slug}.md; ${INDEX_NAME} is generated by lessons.mjs` };
  }
  const slug = name.slice(0, -3);
  if (!SLUG_RE.test(slug)) return { ok: false, error: `lesson filename must be a lowercase-hyphen slug: ${name}` };
  const parsed = parseLesson(content, { defaults: { name: slug, hits: "1", "last-hit": today, evidence: "[]" } });
  if (!parsed.ok) return { ok: false, error: parsed.errors.join("; ") };
  const text = renderLesson({ ...parsed.lesson, name: slug });
  const errors = validateLesson(name, text, { files: repoFiles(ws) });
  if (errors.length) return { ok: false, error: errors.join("; ") };
  writeIndex({ workspaceRoot: ws, pending: { [name]: text } });
  return { ok: true, path: abs, content: text };
}

/** Another occurrence. The same evidence twice counts once, so a retried hit converges. */
export function hitLesson({ workspaceRoot, slug, evidence, today = utcDate() }) {
  const ws = workspaceRoot || resolveRoots().checkout;
  const file = lessonPath(ws, slug);
  if (!fs.existsSync(file)) return { ok: false, error: `no lesson ${slug}; write ${LESSONS_DIR}/${slug}.md first` };
  const parsed = parseLesson(fs.readFileSync(file, "utf8"));
  if (!parsed.ok) return { ok: false, error: parsed.errors.join("; ") };
  const l = parsed.lesson;
  if (l.evidence.includes(evidence)) return { ok: true, path: file, hits: l.hits };
  const next = {
    ...l,
    hits: l.hits + 1,
    lastHit: today,
    evidence: [...l.evidence, evidence].slice(-MAX_EVIDENCE),
  };
  writeLesson(ws, slug, renderLesson(next));
  return { ok: true, path: file, hits: next.hits };
}

export function removeLesson({ workspaceRoot, slug }) {
  const ws = workspaceRoot || resolveRoots().checkout;
  const file = lessonPath(ws, slug);
  if (!fs.existsSync(file)) return { ok: false, error: `no lesson ${slug}` };
  fs.rmSync(file);
  writeIndex({ workspaceRoot: ws });
  return { ok: true };
}

export function checkLessons({ workspaceRoot }) {
  const ws = workspaceRoot || resolveRoots().checkout;
  const dir = lessonsDir(ws);
  if (!fs.existsSync(dir)) return [];
  const errors = [];
  const files = repoFiles(ws);
  for (const name of lessonFiles(ws)) {
    for (const e of validateLesson(name, fs.readFileSync(path.join(dir, name), "utf8"), { files })) {
      errors.push(`${LESSONS_DIR}/${name}: ${e}`);
    }
  }
  let onDisk = null;
  try {
    onDisk = fs.readFileSync(path.join(dir, INDEX_NAME), "utf8");
  } catch {
    onDisk = null;
  }
  if (onDisk !== renderIndex(indexRows(ws))) {
    errors.push(`${LESSONS_DIR}/${INDEX_NAME} is out of date; run node .rulesync/scripts/lessons.mjs index`);
  }
  return errors;
}

function fail(msg) {
  process.stderr.write(`${msg}\n`);
  return 1;
}

function main(argv) {
  const roots = resolveRoots();
  const ws = roots.checkout;
  const [cmd, ...rest] = argv;
  if (cmd === "match") {
    if (!rest.length) return fail(USAGE);
    for (const r of matchLessons({ workspaceRoot: ws, files: rest.map((f) => path.resolve(roots.cwd, f)) })) {
      process.stdout.write(`${r.file} (hits ${r.hits}): ${r.summary}\n`);
    }
    return 0;
  }
  if (cmd === "hit") {
    const at = rest.indexOf("--evidence");
    const slug = rest[0];
    const evidence = at === -1 ? "" : rest[at + 1];
    if (!slug || slug === "--evidence" || !evidence) return fail(USAGE);
    const r = hitLesson({ workspaceRoot: ws, slug, evidence });
    if (!r.ok) return fail(r.error);
    process.stdout.write(`${LESSONS_DIR}/${slug}.md hits ${r.hits}\n`);
    return 0;
  }
  if (cmd === "rm") {
    if (!rest[0]) return fail(USAGE);
    const r = removeLesson({ workspaceRoot: ws, slug: rest[0] });
    return r.ok ? 0 : fail(r.error);
  }
  if (cmd === "index" && !rest.length) {
    writeIndex({ workspaceRoot: ws });
    return 0;
  }
  if (cmd === "check" && !rest.length) {
    const errors = checkLessons({ workspaceRoot: ws });
    if (!errors.length) return 0;
    return fail(errors.join("\n"));
  }
  return fail(USAGE);
}

const thisFile = fileURLToPath(import.meta.url);
const invoked = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (invoked === thisFile || import.meta.url === pathToFileURL(invoked).href) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (err) {
    process.exit(fail(String(err && err.message ? err.message : err)));
  }
}
